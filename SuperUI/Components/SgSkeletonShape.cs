namespace SuperUI.Components;

/// <summary>
/// Defines the shape of a primitive <see cref="SgSkeleton"/> placeholder.
/// </summary>
public enum SgSkeletonShape
{
    /// <summary>Single-line text placeholder (default).</summary>
    Text,
    /// <summary>Rectangular block placeholder.</summary>
    Rect,
    /// <summary>Circular placeholder (e.g. avatar).</summary>
    Circle
}
