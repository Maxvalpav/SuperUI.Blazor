namespace SuperUI.Components;

/// <summary>
/// Defines the language hint for syntax highlighting.
/// </summary>
public enum SgCodeLanguage
{
    /// <summary>Plain text — no highlighting.</summary>
    Text,
    /// <summary>Razor / Blazor markup.</summary>
    Razor,
    /// <summary>C# source code.</summary>
    CSharp,
    /// <summary>HTML markup.</summary>
    Html,
    /// <summary>CSS stylesheet.</summary>
    Css,
    /// <summary>JSON data.</summary>
    Json,
    /// <summary>JavaScript source code.</summary>
    JavaScript,
    /// <summary>TypeScript source code.</summary>
    TypeScript,
    /// <summary>XML markup.</summary>
    Xml,
    /// <summary>Bash / shell script.</summary>
    Bash,
    /// <summary>SQL query.</summary>
    Sql
}
