namespace SuperUI.Components;

/// <summary>
/// Controls the horizontal alignment of the label text inside a <see cref="SgDivider"/>.
/// </summary>
public enum SgDividerAlign
{
    /// <summary>Centers the label text (default).</summary>
    Center,

    /// <summary>Aligns the label text to the left.</summary>
    Left,

    /// <summary>Aligns the label text to the right.</summary>
    Right
}
