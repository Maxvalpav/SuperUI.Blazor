/// </summary>
public enum SgBadgeVariant
{
    /// <summary>Default neutral style.</summary>
    Default,
    /// <summary>Success / positive state (green).</summary>
    Success,
    /// <summary>Danger / error state (red).</summary>
    Danger,
    /// <summary>Warning state (yellow/orange).</summary>
    Warn,
    /// <summary>Muted / inactive state (gray).</summary>
    Muted,
    /// <summary>Informational state (blue).</summary>
    Info
}
