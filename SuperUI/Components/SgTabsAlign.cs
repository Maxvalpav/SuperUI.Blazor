namespace SuperUI.Components;

/// <summary>
/// Controls how tabs are aligned along the strip.
/// </summary>
public enum SgTabsAlign
{
    /// <summary>Align to the start of the strip (default).</summary>
    Start,
    /// <summary>Center tabs along the strip.</summary>
    Center,
    /// <summary>Align tabs to the end of the strip.</summary>
    End,
    /// <summary>Each tab grows to fill the strip equally.</summary>
    Stretch
}
