namespace SuperUI.Components;

/// <summary>
/// Defines the position of the <see cref="SgSpinner"/> DisplayLabel relative to the spinner.
/// </summary>
public enum SgSpinnerLabelPosition
{
    /// <summary>Label appears to the right of the spinner (default).</summary>
    Right,

    /// <summary>Label appears to the left of the spinner.</summary>
    Left,

    /// <summary>Label appears below the spinner.</summary>
    Bottom,

    /// <summary>Label appears above the spinner.</summary>
    Top
}