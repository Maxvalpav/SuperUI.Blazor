namespace SuperUI.Components;

/// <summary>
/// Defines the HTML <c>type</c> attribute values for the <see cref="SgButton"/> component.
/// </summary>
public enum SgButtonType
{
    /// <summary>Standard button (default). Does not submit forms.</summary>
    Button,
    /// <summary>Submits the enclosing form.</summary>
    Submit,
    /// <summary>Resets the enclosing form.</summary>
    Reset
}
