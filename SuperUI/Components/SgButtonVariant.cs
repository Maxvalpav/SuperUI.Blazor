namespace SuperUI.Components;

/// <summary>
/// Defines the visual variant options for the <see cref="SgButton"/> component.
/// </summary>
public enum SgButtonVariant
{
    /// <summary>Default neutral button.</summary>
    Default,
    /// <summary>Primary action button (accent color).</summary>
    Primary,
    /// <summary>Danger / destructive action (red).</summary>
    Danger,
    /// <summary>Success / positive action (green).</summary>
    Success,
    /// <summary>Ghost button — transparent background.</summary>
    Ghost,
    /// <summary>Outlined button — border only.</summary>
    Outlined,
    /// <summary>Dashed border button.</summary>
    Dashed
}
