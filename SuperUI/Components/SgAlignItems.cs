namespace SuperUI.Components;

/// <summary>
/// Defines the cross-axis alignment of items in <see cref="SgStack"/>.
/// Maps to CSS <c>align-items</c>.
/// </summary>
public enum SgAlignItems
{
    /// <summary>Items stretch to fill the container (default).</summary>
    Stretch,
    /// <summary>Items align to the start of the cross axis.</summary>
    Start,
    /// <summary>Items align to the center of the cross axis.</summary>
    Center,
    /// <summary>Items align to the end of the cross axis.</summary>
    End
}
