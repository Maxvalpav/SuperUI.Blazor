namespace SuperUI.Enums;

/// <summary>Animation style for skeleton placeholders.</summary>
public enum SgSkeletonAnimation
{
    /// <summary>Shimmer sweep (default) — a gradient highlight moves diagonally across the element.</summary>
    Wave,

    /// <summary>Single bright highlight that sweeps left to right.</summary>
    Shine,

    /// <summary>Gentle opacity pulse (breathing effect).</summary>
    Pulse,

    /// <summary>Fades in and out rhythmically.</summary>
    Fade,

    /// <summary>Scales up and down gently.</summary>
    Scale
}
