namespace SuperUI.Enums;

/// <summary>Placement of the dropdown opened from <c>SgRibbonSplit</c>.</summary>
public enum SgRibbonSplitPlacement
{
    /// <summary>Below the button, aligned to the left edge.</summary>
    BottomStart = 0,
    /// <summary>Below the button, aligned to the right edge (default).</summary>
    BottomEnd = 1,
    /// <summary>Below the button, centred.</summary>
    Bottom = 2,
    /// <summary>To the right of the button, aligned to the top.</summary>
    RightStart = 3,
    /// <summary>To the right of the button, aligned to the bottom.</summary>
    RightEnd = 4
}
