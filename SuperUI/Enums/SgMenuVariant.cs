namespace SuperUI.Enums;

/// <summary>Defines visual variants for the <c>SgMenu</c> container.</summary>
public enum SgMenuVariant
{
    /// <summary>Default menu with border and shadow.</summary>
    Default,
    /// <summary>Menu with a visible border, no shadow.</summary>
    Bordered,
    /// <summary>Menu with elevated shadow, no border.</summary>
    Elevated,
    /// <summary>Ghost menu with no border or shadow (transparent).</summary>
    Ghost
}
